-- latest action for JEST

SELECT 
 IFLOT.OBJNR
 , IFLOT.TPLNR
 , JEST.STAT
 , JEST.INACT
 , JEST.CHGNR
 , TJ02T.TXT04
 , TJ02T.TXT30
 , JCDS.UDATE
 , JCDS.UTIME

FROM SRCSAPECC_MY..IFLOT AS IFLOT
JOIN SRCSAPECC_MY..JEST AS JEST
    ON IFLOT.OBJNR = JEST.OBJNR
JOIN SRCSAPECC_MY..TJ02T AS TJ02T
    ON JEST.STAT = TJ02T.ISTAT
JOIN SRCSAPECC_MY..JCDS AS JCDS
    ON JCDS.OBJNR = IFLOT.OBJNR AND JCDS.STAT = JEST.STAT
WHERE 1=1
    AND JEST.OBJNR = 'IF?0100000000000004806'
    AND TJ02T.SPRAS = 'E'

ORDER BY JCDS.UDATE DESC, JCDS.UTIME DESC
;



